/**
 * Phonetic mapper for transliterating English names into Pharaonic glyphs
 */
export const transliterateToHieroglyphs = (text: string): { glyphs: string; letters: { char: string; glyph: string; gardiner: string }[] } => {
  const clean = text.toLowerCase().replace(/[^a-z]/g, '');
  const result: { char: string; glyph: string; gardiner: string }[] = [];

  const map: Record<string, { glyph: string; gardiner: string }> = {
    a: { glyph: '𓄿', gardiner: 'G1' },
    b: { glyph: '𓃀', gardiner: 'D58' },
    c: { glyph: '𓎡', gardiner: 'V31' },
    d: { glyph: '𓂧', gardiner: 'D46' },
    e: { glyph: '𓇋', gardiner: 'M17' },
    f: { glyph: '𓆑', gardiner: 'I9' },
    g: { glyph: '𓎼', gardiner: 'W11' },
    h: { glyph: '𓉔', gardiner: 'O4' },
    i: { glyph: '𓇋', gardiner: 'M17' },
    j: { glyph: '𓆓', gardiner: 'I10' },
    k: { glyph: '𓎡', gardiner: 'V31' },
    l: { glyph: '𓂋', gardiner: 'D21' }, // In ancient Egyptian L was written using R or lioness
    m: { glyph: '𓅓', gardiner: 'G17' },
    n: { glyph: '𓈖', gardiner: 'N35' },
    o: { glyph: '𓅱', gardiner: 'G43' },
    p: { glyph: '𓊪', gardiner: 'Q3' },
    q: { glyph: '𓈎', gardiner: 'N29' },
    r: { glyph: '𓂋', gardiner: 'D21' },
    s: { glyph: '𓋴', gardiner: 'S29' },
    t: { glyph: '𓏏', gardiner: 'X1' },
    u: { glyph: '𓅱', gardiner: 'G43' },
    v: { glyph: '𓆑', gardiner: 'I9' },
    w: { glyph: '𓅱', gardiner: 'G43' },
    x: { glyph: '𓎡𓋴', gardiner: 'V31+S29' },
    y: { glyph: '𓇌', gardiner: 'M17A' },
    z: { glyph: '𓊃', gardiner: 'O34' },
  };

  for (const ch of clean) {
    if (map[ch]) {
      result.push({ char: ch.toUpperCase(), glyph: map[ch].glyph, gardiner: map[ch].gardiner });
    }
  }

  const combinedGlyphs = result.map(r => r.glyph).join(' ');
  return { glyphs: combinedGlyphs, letters: result };
};
